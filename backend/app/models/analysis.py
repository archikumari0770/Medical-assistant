"""
Schemas for the decision-support ("analysis") pipeline output.

These are pure Pydantic (no DB table) — an analysis is computed on
demand from the patient's data + knowledge graph + RAG context, not
stored as a row (though you may want to persist runs to Postgres later
for audit purposes; see app/audit/logger.py).
"""
from __future__ import annotations

import uuid
from datetime import datetime

from pydantic import BaseModel, Field


class AnalysisRequest(BaseModel):
    patient_id: uuid.UUID
    symptoms: list[str] = Field(default_factory=list)
    free_text: str = ""  # e.g. raw clinical note to extract symptoms from


class EvidenceItem(BaseModel):
    source: str  # e.g. "knowledge_graph", "patient_history", "medical_literature"
    description: str
    reference_id: str | None = None


class CandidateCondition(BaseModel):
    name: str
    score: float  # 0-1 relative likelihood, NOT a calibrated probability
    supporting_evidence: list[EvidenceItem] = Field(default_factory=list)
    conflicting_evidence: list[EvidenceItem] = Field(default_factory=list)
    uncertainty_notes: str = ""


class SafetyFlag(BaseModel):
    severity: str  # "info" | "warning" | "critical"
    message: str
    triggered_by: str


class AnalysisResult(BaseModel):
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    patient_id: uuid.UUID
    created_at: datetime = Field(default_factory=datetime.utcnow)
    candidates: list[CandidateCondition] = Field(default_factory=list)
    safety_flags: list[SafetyFlag] = Field(default_factory=list)
    narrative_summary: str = ""
    disclaimer: str = (
        "This output is generated by a research prototype for decision "
        "support only. It is not a diagnosis and must be reviewed by a "
        "qualified clinician before any clinical action is taken."
    )
